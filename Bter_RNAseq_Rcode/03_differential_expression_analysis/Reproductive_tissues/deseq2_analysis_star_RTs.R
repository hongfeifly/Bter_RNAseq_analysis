## Subset genes with evidence of significantly differential expression:
deseq_object_worker_bias <- subset(x = deseq_object_results,
                                   padj < 0.05 &
                                     log2FoldChange >= 1)
nrow(deseq_object_worker_bias)

## Subset genes with evidence of significantly differential expression:
deseq_object_queen_bias <- subset(x = deseq_object_results,
                                  padj < 0.05 &
                                    log2FoldChange <= -1)
nrow(deseq_object_queen_bias)

## Plot volcano plot of:
## a) Log2FoldChange (gene expression) against:
## b) -log10 transformed p-value (significant threshold)

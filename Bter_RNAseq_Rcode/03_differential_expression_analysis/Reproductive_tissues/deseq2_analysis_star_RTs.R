## Create function for plotting:
plotPCA.san <- function(object,
                        first_pc = first_pca,
                        second_pc = second_pca,
                        intgroup = "condition",
                        ntop = 1000,
                        returnData = FALSE) {
  rv <- rowVars(assay(object))
  select <- order(rv, decreasing = TRUE)[seq_len(min(ntop,
                                                     length(rv)))]
  pca <- prcomp(t(assay(object)[select, ]))
  #return(pca)
  percentVar <- pca$sdev ^ 2 / sum(pca$sdev ^ 2)
  if (!all(intgroup %in% names(colData(object)))) {
    stop("the argument 'intgroup' should specify columns of colData(dds)")
  }
  intgroup.df <- as.data.frame(colData(object)[, intgroup, drop = FALSE])
  group <- if (length(intgroup) > 1) {
    factor(apply(intgroup.df, 1,
                 paste,
                 collapse = " : "))
  }
  else {
    colData(object)[[intgroup]]
  }
  ## Select the PCAs and percentVar that you like instead of 1 and 2
  d <- data.frame(PC1 = pca$x[, first_pc],
                  PC2 = pca$x[, second_pc],
                  group = group, 
                  intgroup.df,
                  name = colData(vsd)[,1])
  if (returnData) {
    attr(d, "percentVar") <- percentVar[first_pc:second_pc]
    return(d)
  }
  ggplot(data = d,
         aes_string(x = "PC1",
                    y = "PC2",
                    color = "group")) +
    geom_point(data = d,
               aes(fill = group),
               colour = "black",
               pch = 21,
               size = 3) +
    xlab(paste0("PC", first_pc, ": ",
                round(percentVar[first_pc] * 100),
                "%")) +
    ylab(paste0("PC", second_pc, ": ",
                round(percentVar[second_pc] * 100),
                "%")) +
    #coord_fixed() +
    #geom_text_repel(size = 3) +
    theme_bw() +
    theme(axis.title = element_text(size = 12,
                                    face = "bold"),
          axis.text = element_text(size = 10,
                                   face = "plain"),
          legend.title = element_text(size = 12,
                                      face = "bold"),
          legend.text = element_text(size = 12,
                                     face = "plain"),
          legend.position = "none")
}

